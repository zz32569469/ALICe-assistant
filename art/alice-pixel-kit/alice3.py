import sys
from PIL import Image, ImageDraw
import shade
from calib2 import cleanup

shade.RAMPS.clear()
shade.RAMPS.update({   # 每種材質 4 色：外框、陰影、底色、亮面
 "h": ["#56618a", "#8f9cc0", "#c6d0e6", "#eef2fa"],
 "s": ["#b0706a", "#f0b8a6", "#fde0d2", "#fff2ea"],
 "j": ["#1e2234", "#353b56", "#4f577a", "#6e78a0"],
 "t": ["#16172a", "#25273b", "#36394f", "#484c66"],
 "k": ["#16172a", "#27293d", "#3b3e56", "#4e526c"],
 "b": ["#1f4fa0", "#3a7fd6", "#62a4ee", "#9cc8f8"],
 "w": ["#6b7088", "#c0c6d6", "#eef1f7", "#ffffff"],
 "r": ["#16172a", "#26283c", "#3d4160", "#52577a"],
 "n": ["#4a4e60", "#8a8fa3", "#c4c8d4", "#e2e5ec"],
})
shade.FIXED.clear(); shade.FIXED.update({
 "e": "#1e2a3c", "E": "#2f9474", "Q": "#79d6b0", "W": "#ffffff", "P": "#f9c4be", "m": "#c0605e"})
shade.CASTERS = {"h"}
shade.LIGHTEN = {"L": "h"}
CODES = ".hsjtkbwrneEmHJTKSLQWP"

def build(Wpx, Hpx, stage):
    sx, sy = 48/100, Hpx/140
    ox = (Wpx - 48) / 2
    img = Image.new("L", (Wpx, Hpx), 0); d = ImageDraw.Draw(img)
    ident = lambda x: x
    cur = [ident]
    k = lambda m: CODES.index(m)
    tf = lambda pts: [(cur[0](x)*sx + ox, y*sy) for x,y in pts]
    def tb(b):
        x0, x1 = sorted((cur[0](b[0]), cur[0](b[2])))
        return (x0*sx+ox, b[1]*sy, x1*sx+ox, b[3]*sy)
    P = lambda m, pts: d.polygon(tf(pts), fill=k(m))
    E = lambda m, b: d.ellipse(tb(b), fill=k(m))
    R = lambda m, b: d.rectangle(tb(b), fill=k(m))
    L = lambda m, pts, w=1: d.line(tf(pts), fill=k(m), width=w)
    s2, s3, s4, s5 = stage >= 2, stage >= 3, stage >= 4, stage >= 5
    WIDE = (lambda x: 50 + (x-50)*(1.1 if s5 else 1.06 if s4 else 1.15)) if s2 else ident
    if s5: shade.RAMPS['n'] = ['#2a2c35', '#4a4d58', '#6a6d78']
    if s4: shade.RAMPS["j"] = ["#191b24", "#2a2d3b", "#3e4256", "#555a72", "#6f758e"]

    # 後髮
    if s4: P("h", [(50,10),(66,14),(71,34),(72,60),(75,88),(76,101),(71,96),(69,105),(65,95),(62,102),(59,90),(57,60),(55,40)])
    else: P("h", [(50,10),(68,14),(74,34),(76,60),(80,88),(81,101),(75,96),(73,105),(68,95),(65,103),(61,90),(58,60),(55,40)])
    P("h", [(30,40),(37,44),(37,70),(33,82),(28,73)])
    if s2:
        if s4: L("H", [(63,30),(66,92)]); L("H", [(68,40),(72,94)]); L("H", [(60,46),(61,88)])
        else: L("H", [(64,30),(68,92)]); L("H", [(70,40),(76,94)]); L("H", [(60,44),(63,88)])
    # 腿
    P("s", [(52,92),(60,92),(59,99),(53,99)])
    P("k", [(53,99),(59,99),(61,113),(60,124),(54,124),(53,113)])
    P("s", [(40,92),(48,92),(47,99),(41,99)])
    P("k", [(41,99),(47,99),(47,114),(46,124),(41,124),(40,114)])
    if s3:
        L("k", [(43,89),(43,99)]); L("k", [(57,89),(57,99)])          # 吊帶
        R("n", (42.5,98,43.5,99)); R("n", (56.5,98,57.5,99))          # 扣環
        L("K", [(44,104),(43,118)])
    P("w", [(51,121),(62,121),(65,131),(51,131)])
    P("w", [(35,122),(48,122),(48,132),(33,132),(33,127)])
    if s3:
        L("r", [(33,131),(48,131)]); L("r", [(51,130),(65,130)])      # 鞋底
        R("k", (39,124,45,125)); R("k", (54,123,60,124))              # 鞋帶
        R("b", (46,126,48,128))                                       # 鞋側藍標
    # 內搭、肩膀、短褲
    P("s", [(36,54),(64,54),(66,60),(34,60)])
    P("t", [(42,53),(56,53),(59,60),(57,74),(58,84),(41,84),(42,74),(39,60)])
    P("t", [(40,82),(60,82),(61,92),(51,92),(50,88),(48,92),(39,92)])
    if s2: L("T", [(49,62),(48,82)])
    # 外套（加寬、敞開、掛在手肘）
    cur[0] = WIDE
    P("j", [(57,60),(66,58),(72,76),(74,100),(58,100),(59,80)])
    P("j", [(34,58),(42,60),(44,78),(43,100),(26,102),(24,80),(26,64)])
    if s2:
        L("J", [(36,80),(31,100)]); L("J", [(65,76),(70,98)]); L("J", [(40,86),(38,100)])
    if s3:
        L("n", [(43,66),(43.5,96)] if s5 else [(43,64),(43.5,98)])     # 拉鍊
        R("n", (42,80,44,82))
    # 遠側袖子
    P("j", [(62,57),(70,60),(77,76),(72,90),(64,92),(68,78),(63,66)])
    if s4: L("J", [(62,57),(70,60),(77,76),(72,90),(64,92),(68,78),(63,66),(62,57)])
    if s2: L("J", [(68,64),(73,78)])
    L("t", [(64,90),(70,88)])
    if s4: L("b", [(66,73),(76,75)])
    elif s3: R("b", (70,72,74,75))
    # 近側袖子：手肘往外、手插口袋
    P("j", [(30,56),(41,59),(37,74),(40,88),(30,92),(20,78),(24,62)])
    if s4: L("J", [(41,59),(37,74),(40,88),(30,92)])
    if s2: L("J", [(28,64),(23,77)]); L("J", [(33,76),(29,88)])
    L("t", [(30,88),(38,92)])
    if s3:
        if s4:
            L("b", [(22,69),(37,71)]); L("b", [(25,83),(39,85)])
            L("b", [(23,71),(19,82)]); R("n", (22,69,23,70))
        else:
            R("b", (22,70,27,73)); R("b", (27,84,31,87))
            L("b", [(25,73),(23,81)])                                     # 垂下的綁帶
            R("n", (24,72,25,73))
    cur[0] = ident
    # 脖子、頭
    R("t", (44,45,53,54))
    E("h", (33,6,68,46) if s4 else (32,6,70,46))
    if s5: P("s", [(36,23),(60,21),(62,32),(57,41),(49,45),(42,42),(36,35)])
    else: P("s", [(36,23),(60,21),(62,33),(57,43),(48,48),(41,44),(36,36)])
    P("h", [(33,18),(64,14),(64,28),(60,25),(58,31),(55,24),(51,31),(48,24),(44,30),(41,24),(37,30),(35,24)])
    P("h", [(33,24),(37,25),(38,44),(37,60),(34,63),(31,46)])        # 近側鬢髮
    if s2:
        L("H", [(36,30),(35,56)]); L("H", [(66,20),(68,40)])
        L("H", [(46,10),(40,22)]); L("H", [(56,10),(60,22)])
    if s3:
        L("L", [(40,13),(56,10)]); L("L", [(56,10),(64,15)])          # 髮頂光澤
    # 臉（動漫眼：睫毛、瞳孔、亮點、下緣淺色）
    R("e", (49,28,56,29)); R("E", (50,30,55,34)); R("Q", (50,34,55,34)); R("W", (53,30,54,31))
    R("e", (39,28,44,29)); R("E", (40,30,43,34)); R("Q", (40,34,43,34)); R("W", (42,30,42,31))
    R("P", (38,38,39,38)); R("P", (56,37,58,37))
    R("m", (47,41,48,41))
    # 蝴蝶結、緞帶、X 髮夾
    P("r", [(26,10),(35,13),(27,18)]); P("r", [(35,13),(44,8),(44,17)]); E("r", (33,11,37,15))
    if s3:
        L("b", [(34,15),(31,27)]); L("b", [(36,15),(37,24)])
        L("r", [(62,19),(66,23)]); L("r", [(66,19),(62,23)])
    rows = ["".join(CODES[img.getpixel((x,y))] for x in range(Wpx)) for y in range(Hpx)]
    return cleanup(rows) if stage >= 3 else rows

def run(stage, W=52, H=68, sc=6):
    img = shade.render(build(W, H, stage), strands=False)
    big = img.resize((W*sc, H*sc), Image.NEAREST)
    bg = Image.new("RGBA", big.size, "#e9e6f0"); bg.alpha_composite(big)
    bg.convert("RGB").save(f"b_stage{stage}.png"); img.save(f"b_stage{stage}_1x.png")

if __name__ == "__main__":
    for st in map(int, sys.argv[1:]): run(st)
