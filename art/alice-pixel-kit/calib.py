"""原創校準角色：戴兜帽的老行商，拄著掛提燈的手杖，背著大背包。"""
from PIL import Image, ImageDraw
import shade

shade.RAMPS.update({
 "c": ["#2a211c", "#45362c", "#634e3f", "#816753", "#9f8469"],   # 斗篷
 "s": ["#6a4638", "#a46e58", "#c48d74", "#dcae93"],               # 皮膚
 "f": ["#47433f", "#75706a", "#a29c93", "#cbc5ba"],               # 鬍子眉毛
 "p": ["#202328", "#343841", "#4b505b", "#646a76"],               # 褲子/鋪蓋
 "o": ["#1c1712", "#31271d", "#4a3a2a", "#624c37"],               # 靴子
 "a": ["#382b1d", "#5a4630", "#7f6545", "#a1865e"],               # 背包/皮革
 "r": ["#3a1918", "#5e2a26", "#843d35", "#a05646"],               # 圍巾
 "g": ["#1d2820", "#2d3f32", "#425848", "#5a7260"],               # 內衫
 "d": ["#281e16", "#463526", "#664c35"],                          # 木杖/腰帶
 "n": ["#26272c", "#474952", "#727581"],                          # 金屬
 "y": ["#8a6a2a", "#d0a043", "#f2d585"],                          # 燈光
})
shade.FIXED.update({"e": "#1a1412", "Y": "#fff3c4"})
shade.CASTERS = {"c"}
CODES = ".cs fporgdnyeYa".replace(" ", "")

def build(Wpx, Hpx):
    sx, sy = Wpx/100, Hpx/140
    img = Image.new("L", (Wpx, Hpx), 0); d = ImageDraw.Draw(img)
    k = lambda m: CODES.index(m)
    P = lambda m, pts: d.polygon([(x*sx, y*sy) for x,y in pts], fill=k(m))
    E = lambda m, b: d.ellipse((b[0]*sx,b[1]*sy,b[2]*sx,b[3]*sy), fill=k(m))
    R = lambda m, b: d.rectangle((b[0]*sx,b[1]*sy,b[2]*sx,b[3]*sy), fill=k(m))
    L = lambda m, pts, w=1: d.line([(x*sx, y*sy) for x,y in pts], fill=k(m), width=w)

    E("p", (52,20,84,34))                                   # 鋪蓋捲
    P("a", [(54,30),(79,33),(81,74),(57,76)])               # 背包
    R("d", (60,46,79,49))                                   # 背包皮帶
    L("d", [(25,18),(29,134)], 2)                           # 手杖
    L("n", [(25,18),(18,22)], 1)                            # 吊鉤
    R("n", (12,23,23,39)); R("y", (14,26,21,36)); R("Y", (16,29,19,33))
    P("p", [(52,94),(61,94),(62,118),(53,118)])             # 後腳
    P("o", [(51,116),(63,116),(66,132),(51,132)])
    P("p", [(38,94),(48,94),(45,117),(36,117)])             # 前腳跨步
    P("o", [(33,115),(46,115),(46,132),(27,132),(28,126)])
    P("c", [(35,40),(64,40),(71,70),(75,112),(61,116),(51,109),(41,116),(28,111),(31,70)])  # 斗篷
    P("g", [(42,54),(54,54),(57,96),(40,96)])               # 內衫
    R("d", (40,79,57,83)); R("a", (54,82,60,90))            # 腰帶與小袋
    P("c", [(33,43),(43,47),(38,66),(32,74),(24,71),(27,57)])  # 握杖的手臂
    E("s", (24,66,32,75))                                   # 手
    L("d", [(27,64),(28,78)], 2)                            # 手杖從手中穿過
    P("c", [(31,27),(36,12),(48,5),(62,8),(69,22),(69,43),(60,45),(36,45),(31,39)])  # 兜帽
    P("s", [(37,22),(55,20),(57,32),(51,40),(42,40),(37,32)])  # 臉
    P("s", [(35,28),(38,28),(38,31),(35,31)])               # 鼻子
    P("f", [(38,32),(55,30),(56,38),(51,49),(44,51),(39,42)])  # 鬍子
    L("f", [(40,25),(44,24)], 1); L("f", [(48,24),(53,25)], 1)  # 眉毛
    R("e", (41,27,43,27)); R("e", (49,27,51,27))
    P("c", [(35,23),(41,15),(54,14),(59,19),(58,24),(51,19),(42,20),(37,27)])  # 兜帽邊緣
    P("r", [(35,40),(58,38),(61,46),(51,49),(35,48)])       # 圍巾
    P("r", [(52,46),(59,46),(61,63),(54,65)])
    return ["".join(CODES[img.getpixel((x,y))] for x in range(Wpx)) for y in range(Hpx)]

if __name__ == "__main__":
    out = []
    for W,H,sc in [(44,62,7)]:
        img = shade.render(build(W,H), strands=False)
        img.save(f"calib_{W}x{H}.png")
        big = img.resize((W*sc,H*sc), Image.NEAREST)
        bg = Image.new("RGBA", big.size, "#e9e6f0"); bg.alpha_composite(big)
        bg.convert("RGB").save(f"calib_{W}x{H}_big.png")
